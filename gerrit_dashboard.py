#!/usr/bin/env python3
"""Build the OpenStack patch dashboard (single HTML file) from OpenDev Gerrit.

Read-only: only GET requests against the public REST API.
Usage: gerrit_dashboard.py [output.html]

Accounts to track come from accounts.json next to this script (see README.md).
"""
import datetime as dt
import json
import os
import re
import sys
import urllib.parse
import urllib.request

GERRIT = "https://review.opendev.org"
HERE = os.path.dirname(os.path.abspath(__file__))
BOT = re.compile(r"\bCI\b|Zuul|Jenkins|\bBot\b|Gate|Pipeline", re.I)
# Third-party CI result comments, in both the one-line ("Patch Set 4: Build failed") and the
# multi-line HPE form ("Patch Set 2:\n\nHPE AlletraMP iSCSI CI\n\nBuild failed.") posted from personal accounts.
RESULT = re.compile(
    r"\s*Patch Set \d+:\s*(Build|Verified|Starting|Check|Recheck|Run)"
    r"|^\s*Patch Set \d+:\s*\n\s*\n\s*\S.*\bCI\b.*\n\s*\n\s*Build (succeeded|failed)",
    re.I,
)
STALE_DAYS = 30
PAGE = 200  # Gerrit returns at most this many changes per request; we page with S= offsets
STANDALONE_HEAD = (
    '<!doctype html><html lang="en"><head><meta charset="utf-8">'
    '<meta name="viewport" content="width=device-width, initial-scale=1, viewport-fit=cover">'
    "<style>body{margin:0}[hidden]{display:none!important}img{max-width:100%}</style></head><body>\n"
)


def get(path, params):
    qs = urllib.parse.urlencode(params, doseq=True)
    req = urllib.request.Request(GERRIT + path + "?" + qs, headers={"User-Agent": "gerrit-dashboard"})
    with urllib.request.urlopen(req, timeout=120) as r:
        body = r.read().decode()
    return json.loads(body.split("\n", 1)[1])  # strip XSSI prefix


def load_accounts(path=os.path.join(HERE, "accounts.json")):
    """Return the configured accounts with their Gerrit numeric ids resolved.

    Each entry: {"label", "id", "username", "emails", "recheck"}. The id is taken from the file if
    present, else looked up from the username, else from the first email that Gerrit knows.
    """
    with open(path, encoding="utf-8") as f:
        accounts = json.load(f)["accounts"]
    for a in accounts:
        a.setdefault("emails", [])
        a.setdefault("recheck", False)
        a["emails"] = [e.lower() for e in a["emails"]]
        if a.get("id"):
            continue
        if a.get("username"):
            try:
                a["id"] = get("/accounts/%s" % urllib.parse.quote(a["username"]), {})["_account_id"]
                continue
            except Exception:  # noqa: BLE001 - fall through to the email lookup
                pass
        for e in a["emails"]:
            hits = get("/accounts/", {"q": "email:" + e})
            if hits:
                a["id"] = hits[0]["_account_id"]
                break
        if not a.get("id"):
            print("warning: no Gerrit account found for %r; only author/committer matches" % a["label"], file=sys.stderr)
    return accounts


def search_query(accounts):
    parts = []
    for a in accounts:
        if a.get("id"):
            parts.append("owner:%d" % a["id"])
        for e in a["emails"]:
            parts += ["author:" + e, "committer:" + e]
    return "status:open (" + " OR ".join(parts) + ")"


def fetch_all(query, options):
    """Follow Gerrit's _more_changes marker so more than one page of results comes back."""
    out, start = [], 0
    while True:
        page = get("/changes/", {"q": query, "o": options, "n": PAGE, "S": start})
        out += page
        if not page or not page[-1].get("_more_changes"):
            return out
        start += len(page)


def parse(ts):
    return dt.datetime.strptime(ts[:19], "%Y-%m-%d %H:%M:%S")


def is_bot(m):
    a = m.get("author", {})
    if RESULT.match(m.get("message", "")):
        return True  # third-party CI posting a build result under a person's account
    return bool(BOT.search(a.get("name", ""))) or str(m.get("tag", "")).startswith("autogenerated")


def whose(c, by_id, by_email):
    """Which configured account this change belongs to, and how (owner / author / committer)."""
    owner_id = c["owner"].get("_account_id")
    if owner_id in by_id:
        return by_id[owner_id], "owner"
    commit = c.get("revisions", {}).get(c.get("current_revision", ""), {}).get("commit", {})
    for role in ("author", "committer"):
        email = commit.get(role, {}).get("email", "").lower()
        if email in by_email:
            return by_email[email], role
    return "?", "search"


def classify(c, now, by_id, by_email):
    labels = c.get("labels", {})
    ver = labels.get("Verified", {}).get("all", [])
    zuul = next((v.get("value", 0) for v in ver if v.get("name") == "Zuul"), 0)
    cr = [
        (v.get("name", "?"), v.get("value", 0))
        for v in labels.get("Code-Review", {}).get("all", [])
        if v.get("value") and v.get("name") != "Zuul"
    ]
    account, via = whose(c, by_id, by_email)
    msgs = c.get("messages", [])
    human = [m for m in msgs if not is_bot(m)]
    # Messages from any tracked account are "ours"; a message carrying a +1 is approval, not a question.
    other = [
        m
        for m in human
        if m["author"].get("_account_id") not in by_id and not re.search(r"Code-Review\+\d", m.get("message", ""))
    ]
    last_other = other[-1] if other else None
    # "Needs reply" is driven only by Gerrit's own signals: an unresolved thread or a human -1.
    # Resolved comments and +1 messages after our last message are not a reply owed.
    unresolved = c.get("unresolved_comment_count", 0)
    neg = [n for n, v in cr if v < 0]
    pos = [n for n, v in cr if v > 0]
    wip = bool(c.get("work_in_progress"))
    conflict = c.get("mergeable") is False
    updated = parse(c["updated"])
    created = parse(c["created"])
    idle = (now - updated).days

    if wip:
        state = "wip"
    elif c.get("submittable") and zuul > 0:
        state = "ready"
    elif conflict:
        state = "conflict"
    elif neg or unresolved:
        state = "feedback"
    elif zuul < 0:
        state = "ci"
    elif pos:
        state = "reviewing"
    else:
        state = "waiting"

    return {
        "n": c["_number"],
        "project": c["project"].split("/")[-1],
        "branch": c["branch"],
        "topic": c.get("topic", ""),
        "subject": c["subject"],
        "state": state,
        "account": account,
        "via": via,
        "owner": "" if via == "owner" else c["owner"].get("name", "someone else"),
        "zuul": zuul,
        "cr": cr,
        "unresolved": unresolved,
        "conflict": conflict,
        "ps": c.get("current_revision_number", 1),
        "idle": idle,
        "age": (now - created).days,
        "stale": idle >= STALE_DAYS,
        "updated": c["updated"][:10],
        "last_other": (last_other["author"].get("name", "?") if last_other else ""),
        "last_other_date": (last_other["date"][:10] if last_other else ""),
        "reviewers": sorted(
            {
                r.get("name", "?")
                for r in c.get("reviewers", {}).get("REVIEWER", [])
                if not BOT.search(r.get("name", ""))
            }
        ),
        "size": c.get("insertions", 0) + c.get("deletions", 0),
    }


def main():
    out = sys.argv[1] if len(sys.argv) > 1 else os.path.join(HERE, "dashboard.html")
    now = dt.datetime.now(dt.timezone.utc).replace(tzinfo=None)
    accounts = load_accounts()
    by_id = {a["id"]: a["label"] for a in accounts if a.get("id")}
    by_email = {e: a["label"] for a in accounts for e in a["emails"]}
    changes = fetch_all(
        search_query(accounts),
        ["DETAILED_LABELS", "CURRENT_REVISION", "CURRENT_COMMIT", "DETAILED_ACCOUNTS", "SUBMITTABLE", "MESSAGES"],
    )
    rows = sorted((classify(c, now, by_id, by_email) for c in changes), key=lambda r: r["updated"], reverse=True)
    counts = {}
    for r in rows:
        counts[r["state"]] = counts.get(r["state"], 0) + 1

    hist_path = os.path.join(HERE, "history.json")
    try:
        with open(hist_path) as f:
            hist = json.load(f)
    except (OSError, ValueError):
        hist = []
    today = now.strftime("%Y-%m-%d")
    hist = [h for h in hist if h["d"] != today] + [{"d": today, "total": len(rows), **counts}]
    hist = hist[-60:]
    try:
        with open(hist_path, "w") as f:
            json.dump(hist, f)
    except OSError:
        pass

    data = {
        "generated": now.strftime("%Y-%m-%d %H:%M UTC"),
        "rows": rows,
        "history": hist,
        "gerrit": GERRIT,
        "accounts": [{"label": a["label"], "username": a.get("username", ""), "id": a.get("id")} for a in accounts],
    }
    with open(os.path.join(HERE, "template.html"), encoding="utf-8") as f:
        tpl = f.read()
    blob = json.dumps(data).replace("</", "<\\/")
    page = tpl.replace("/*__DATA__*/null", blob)
    with open(out, "w", encoding="utf-8", newline="\n") as f:
        f.write(page)
    # The artifact viewer wraps the page in its own <html>/<head>; GitHub Pages serves the file as-is,
    # so index.html next to the output gets a minimal skeleton matching the viewer's reset.
    standalone = os.path.join(os.path.dirname(os.path.abspath(out)), "index.html")
    with open(standalone, "w", encoding="utf-8", newline="\n") as f:
        f.write(STANDALONE_HEAD + page + "\n</body></html>\n")
    per_account = {}
    for r in rows:
        per_account[r["account"]] = per_account.get(r["account"], 0) + 1
    print("wrote %s and index.html (%d changes: %s; by account: %s)" % (out, len(rows), counts, per_account))


if __name__ == "__main__":
    main()
